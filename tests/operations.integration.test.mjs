import test from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'vite';
import { GoogleAuthProvider, signInWithCredential, signInWithEmailAndPassword, signOut } from 'firebase/auth';
import { doc, getDoc, getDocs, collection, terminate } from 'firebase/firestore';
import { deleteApp } from 'firebase/app';
import { initializeTestEnvironment } from '@firebase/rules-unit-testing';
import { setDoc } from 'firebase/firestore';

test('real operation services connect roster approval, duplicates, locks, private notifications, check-in, and appeals', async t => {
  const vite = await createServer({ mode: 'test', server: { middlewareMode: true }, appType: 'custom' });
  t.after(() => vite.close());
  const firebase = await vite.ssrLoadModule('/src/lib/firebase.ts');
  assert.equal(firebase.app.options.projectId, 'demo-arenahub', 'Integration tests must never use a production project.');
  const operations = await vite.ssrLoadModule('/src/lib/operationsService.ts');
  const { firestoreService } = await vite.ssrLoadModule('/src/lib/firestore.ts');
  const integrity = await vite.ssrLoadModule('/src/lib/integrityService.ts');
  const community = await vite.ssrLoadModule('/src/lib/communityReports.ts');
  const chat = await vite.ssrLoadModule('/src/lib/matchChat.ts');
  const { createBracketFromTeams } = await vite.ssrLoadModule('/src/lib/bracketUtils.ts');
  const env = await initializeTestEnvironment({ projectId: 'demo-arenahub', firestore: { host: '127.0.0.1', port: 8085 } });
  let stopBrackets = () => {};
  t.after(async () => { stopBrackets(); await signOut(firebase.auth); await terminate(firebase.db); await deleteApp(firebase.app); await env.cleanup(); });
  const password = 'ArenaHub-QA-Only-27!';
  const runId = Date.now().toString();
  const identities = {};
  for (const [label, admin] of [['captain', false], ['referee', true]]) {
    const email = `ops-${label}-${runId}@wmsu.edu.ph`;
    const { user } = await signInWithCredential(firebase.auth, GoogleAuthProvider.credential(JSON.stringify({ sub: email, email, email_verified: true, name: `QA ${label}` })));
    identities[label] = { uid: user.uid, email };
    const response = await fetch('http://127.0.0.1:9098/identitytoolkit.googleapis.com/v1/accounts:update?key=demo-arenahub-key', { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: 'Bearer owner' }, body: JSON.stringify({ localId: user.uid, password, customAttributes: JSON.stringify(admin ? { admin: true } : {}) }) });
    assert.ok(response.ok);
    await env.withSecurityRulesDisabled(ctx => setDoc(doc(ctx.firestore(), 'users', user.uid), { uid: user.uid, email, name: `QA ${label}`, status: 'active', role: 'user', emailVerified: true, joinedAt: new Date() }));
    await signOut(firebase.auth);
  }
  const login = async label => { stopBrackets(); stopBrackets = () => {}; await signOut(firebase.auth); await signInWithEmailAndPassword(firebase.auth, identities[label].email, password); };
  const draft = createBracketFromTeams({ title: 'QA tournament operations', teams: [{ name: 'QA Team A' }, { name: 'QA Team B' }], matchFormat: 'Bo1', finalMatchFormat: 'Bo1' });
  draft.gameId = 'game-mlbb'; draft.status = 'published'; draft.matches = draft.matches.map(m => ({ ...m, gameId: 'game-mlbb', scheduledDate: '2026-11-08', scheduledTime: '13:00' }));
  await env.withSecurityRulesDisabled(ctx => setDoc(doc(ctx.firestore(), 'arenahub/brackets'), { publishedBrackets: [JSON.parse(JSON.stringify(draft))], previousPublishedBrackets: [], publicationRevision: 1 }));
  await login('referee');
  await operations.saveTournamentPolicy({ tournamentId: draft.id, gameId: 'game-mlbb', playersRequired: 5, maxSubstitutes: 2, registrationOpen: true });
  await firestoreService.addGame({ id: `qa-game-${runId}`, name: `QA shared game ${runId}`, registeredTeams: 0, visibility: 'Hidden', bannerImage: '/fairplay-mlbb.webp', category: 'QA' });
  assert.ok((await getDoc(doc(firebase.db, 'arenahub/workspace'))).data().games.some(game => game.id === `qa-game-${runId}`));
  stopBrackets = firestoreService.watchLiveBrackets();
  if (!firestoreService.getPublishedBracketById(draft.id)) await new Promise((resolve, reject) => {
    const timer = setTimeout(() => { stop(); reject(new Error('Published bracket subscription timed out.')); }, 5000);
    const stop = firestoreService.subscribe(() => { if (firestoreService.getPublishedBracketById(draft.id)) { clearTimeout(timer); stop(); resolve(); } });
  });
  firestoreService.updateMatchSchedules([{ id: draft.matches[0].id, scheduledDate: '2026-11-08', scheduledTime: '14:00' }]);
  await firestoreService.syncBracketsToCloud();
  assert.ok((await getDocs(collection(firebase.db, 'arenaAnnouncements'))).size > 0);
  const players = (label) => Array.from({ length: 5 }, (_, i) => ({ name: `QA ${label} ${i}`, ign: `${label}-${i}`, studentId: `${runId}-${label}-student-${i}`, accountId: `${runId}-${label}-game-${i}`, substitute: false }));
  const teamA = draft.matches[0].team1, teamB = draft.matches[0].team2;
  const input = (team, roster) => ({ tournamentId: draft.id, teamId: team.id, teamName: team.name, gameId: 'game-mlbb', college: 'QA College', players: roster });
  await login('captain');
  const a = await operations.submitRegistration(input(teamA, players('a')));
  const duplicate = players('b'); duplicate[0].studentId = players('a')[0].studentId;
  const b = await operations.submitRegistration(input(teamB, duplicate));
  await login('referee');
  await operations.reviewRegistration(a, 'approved', 'Verified student records and game account identifiers.');
  await assert.rejects(operations.reviewRegistration(b, 'approved', 'Reviewed the submitted roster against school records.'), /Duplicate registration/);
  await operations.reviewRegistration(a, 'locked', 'Approved roster locked before tournament play.');
  await login('captain');
  await assert.rejects(operations.submitRegistration(input(teamA, players('replacement'))), /approved roster/);
  await operations.submitRegistration(input(teamB, players('b')));
  await login('referee');
  await operations.reviewRegistration(b, 'approved', 'Verified all revised student records and game accounts.');
  await operations.reviewRegistration(b, 'locked', 'Approved roster locked before competition.');
  const publicBracket = (await getDoc(doc(firebase.db, 'arenahub/brackets'))).data().publishedBrackets[0];
  assert.ok(publicBracket.matches[0].team1.players.length === 5);
  assert.ok(!JSON.stringify(publicBracket).includes('studentId'));
  assert.ok(!JSON.stringify(publicBracket).includes('accountId'));
  const matchId = draft.matches[0].id;
  await operations.saveMatchWindow(matchId, draft.id, [a, b], new Date(Date.now() - 60000).toISOString(), new Date(Date.now() + 600000).toISOString());
  await login('captain');
  const registration = { ...(await getDoc(doc(firebase.db, 'tournamentRegistrations', a))).data(), id: a };
  const window = (await getDoc(doc(firebase.db, 'matchWindows', matchId))).data();
  const lineup = players('a').map(p => ({ studentId: p.studentId, accountId: p.accountId })); lineup[0].accountId = 'different-observed-account';
  await operations.submitCheckIn(registration, window, lineup, 'https://youtu.be/qa-evidence');
  await chat.sendMatchChat(matchId, identities.captain.uid, 'QA captain', 'Disposable QA moderation message.');
  const chatMessage = (await getDocs(collection(firebase.db, 'matchChat', matchId, 'messages'))).docs[0];
  await community.reportLiveMessage(matchId, { id: chatMessage.id, author: 'QA captain', text: 'Disposable QA moderation message.' });
  const caseId = await integrity.submitIntegrityCase({ matchId, reason: 'Suspected cheating', details: '[ArenaHub:mlbb]\nVideo evidence for referee review of the full encounter, not an automatic cheating verdict.', evidenceUrl: 'https://youtu.be/qa-evidence' });
  const ownInbox = await getDocs(collection(firebase.db, 'users', identities.captain.uid, 'notifications'));
  assert.ok(ownInbox.size >= 5);
  await login('referee');
  await community.resolveCommunityReport(`${matchId}__${chatMessage.id}__${identities.captain.uid}`, 'remove');
  assert.equal((await getDoc(doc(firebase.db, 'matchChat', matchId, 'messages', chatMessage.id))).exists(), false);
  const checkInId = `${matchId}__${a}`;
  await assert.rejects(operations.reviewCheckIn(checkInId, 'confirmed', 'Confirmed the submitted lineup against the approved records.'), /discrepancies/);
  await operations.reviewCheckIn(checkInId, 'disputed', 'One observed game account differs from the locked roster; referee follow-up required.');
  await login('captain');
  await operations.submitCheckIn(registration, window, players('a').map(p => ({ studentId: p.studentId, accountId: p.accountId })), 'https://youtu.be/corrected-qa-evidence');
  const archived = await getDoc(doc(firebase.db, 'matchCheckIns', checkInId, 'submissions', '1'));
  assert.equal(archived.data().previous.lineup[0].accountId, 'different-observed-account');
  await login('referee');
  await operations.reviewCheckIn(checkInId, 'confirmed', 'Confirmed the corrected lobby evidence against all five locked player accounts.');
  await integrity.reviewIntegrityCase(caseId, 'resolved', 'Inspected the submitted recording and documented the limited evidence.');
  await login('captain'); await integrity.submitCaseAppeal(caseId, 'Please inspect the alternative player perspective before closing the investigation.');
  await login('referee'); await integrity.resolveCaseAppeal(caseId, 'accepted', 'Accepted the request to inspect the additional perspective; original evidence remains preserved.');
  assert.equal((await getDoc(doc(firebase.db, 'integrityCases', caseId, 'appeals', 'appeal'))).data().status, 'accepted');
});
