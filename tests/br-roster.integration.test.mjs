import test from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'vite';
import { signInWithEmailAndPassword, signOut } from 'firebase/auth';
import { collection, doc, getDoc, getDocs, terminate } from 'firebase/firestore';
import { deleteApp } from 'firebase/app';

test('a full CODM BR lobby supports private rosters, check-in, referee decisions and result notifications', async t => {
  const vite = await createServer({ mode: 'test', server: { middlewareMode: true }, appType: 'custom' });
  t.after(() => vite.close());
  const firebase = await vite.ssrLoadModule('/src/lib/firebase.ts');
  assert.equal(firebase.app.options.projectId, 'demo-arenahub');
  t.after(async () => { await signOut(firebase.auth); await terminate(firebase.db); await deleteApp(firebase.app); });
  const operations = await vite.ssrLoadModule('/src/lib/operationsService.ts');
  const { firestoreService } = await vite.ssrLoadModule('/src/lib/firestore.ts');
  const { createPlacementEvent } = await vite.ssrLoadModule('/src/lib/formats/placement.ts');
  const { fromDocs } = await vite.ssrLoadModule('/src/lib/data/tournamentDocs.ts');
  const { saveTournament } = await vite.ssrLoadModule('/src/lib/data/tournamentStore.ts');
  const integrity = await vite.ssrLoadModule('/src/lib/integrityService.ts');
  const run = Date.now();
  const login = email => signInWithEmailAndPassword(firebase.auth, email, 'ArenaHub-QA-Only-27!');
  await login('organizer@wmsu.edu.ph');
  const event = createPlacementEvent({ title: `BR roster QA ${run}`, teams: Array.from({ length: 25 }, (_, i) => ({ name: `BR Squad ${i + 1}`, collegeCode: 'CCS' })), games: 1, config: { pointsTable: [10, 6], killPoints: 1 }, now: run });
  await firestoreService.publishBracket(event, 'Call of Duty Mobile', 'game-codm-br');
  await operations.saveTournamentPolicy({ tournamentId: event.id, gameId: 'game-codm-br', playersRequired: 4, maxSubstitutes: 0, registrationOpen: true });
  const ids = [];
  await login('student@wmsu.edu.ph');
  for (const [i, team] of event.placement.teams.entries()) ids.push(await operations.submitRegistration({ tournamentId: event.id, teamId: team.id, teamName: team.name, gameId: 'game-codm-br', college: team.collegeCode, players: Array.from({ length: 4 }, (_, j) => ({ name: `PRIVATE BR ${i}-${j}`, ign: `Ace ${i}-${j}`, studentId: `${run}-student-${i}-${j}`, accountId: `${run}-account-${i}-${j}`, substitute: false })) }));
  await login('organizer@wmsu.edu.ph');
  for (const id of ids) {
    await operations.reviewRegistration(id, 'approved', 'Verified all four players against the submitted school records.');
    await operations.reviewRegistration(id, 'locked', 'Locked the verified Battle Royale squad before the match.');
  }
  const tournament = (await getDoc(doc(firebase.db, 'tournaments', event.id))).data();
  const roster = (await getDoc(doc(firebase.db, 'tournaments', event.id, 'public', 'rosters'))).data();
  assert.equal(roster.teams.length, 25);
  assert.equal(roster.teams.reduce((count, team) => count + team.players.length, 0), 100);
  assert.ok(!JSON.stringify(roster).includes('PRIVATE BR'));
  assert.ok(!JSON.stringify(roster).includes(`${run}-student`));
  assert.equal(fromDocs(tournament, roster).rosterTeams.reduce((count, team) => count + team.players.length, 0), 100);
  const matchId = event.placement.games[0].id;
  const opens = new Date(Date.now() - 60000).toISOString(), closes = new Date(Date.now() + 600000).toISOString();
  await assert.rejects(operations.saveMatchWindow(matchId, event.id, ids.slice(0, -1), opens, closes), /every participating team/);
  await assert.rejects(operations.saveMatchWindow(matchId, event.id, [...ids.slice(0, -1), ids[0]], opens, closes), /every participating team/);
  await operations.saveMatchWindow(matchId, event.id, ids, opens, closes);
  const window = (await getDoc(doc(firebase.db, 'matchWindows', matchId))).data();
  assert.equal(window.registrationIds.length, 25);
  const registration = { ...(await getDoc(doc(firebase.db, 'tournamentRegistrations', ids[0]))).data(), id: ids[0] };
  const missing = { ...(await getDoc(doc(firebase.db, 'tournamentRegistrations', ids[1]))).data(), id: ids[1] };
  await login('student@wmsu.edu.ph');
  const inbox = await getDocs(collection(firebase.db, 'users', firebase.auth.currentUser.uid, 'notifications'));
  assert.equal(inbox.docs.filter(item => item.data().entityId === matchId && item.data().title === 'Match check-in scheduled').length, 25);
  const lineup = registration.players.map(({ studentId, accountId }) => ({ studentId, accountId }));
  await operations.submitCheckIn(registration, window, lineup, 'https://youtu.be/qa-br-lobby');
  const caseId = await integrity.submitIntegrityCase({ matchId, reason: 'Suspected cheating', details: '[ArenaHub:codm-br]\nDisposable lobby evidence for the referee workflow.', evidenceUrl: 'https://youtu.be/qa-br-lobby' });
  await login('organizer@wmsu.edu.ph');
  const checkInId = `${matchId}__${registration.id}`;
  await operations.reviewCheckIn(checkInId, 'confirmed', 'Confirmed all four squad players against the locked lobby roster.');
  assert.equal((await getDoc(doc(firebase.db, 'matchCheckIns', checkInId))).data().status, 'confirmed');
  await integrity.reviewIntegrityCase(caseId, 'resolved', 'Reviewed both lobby perspectives and confirmed the tournament rule violation.');
  await operations.recordSanction(registration, 'warning', caseId, 'Recorded a warning for this squad after the resolved lobby review.');
  assert.equal((await getDoc(doc(firebase.db, 'tournamentRegistrations', registration.id))).data().sanction, 'warning');
  await operations.saveMatchWindow(matchId, event.id, ids, new Date(Date.now() - 120000).toISOString(), new Date(Date.now() - 60000).toISOString());
  const expiredWindow = (await getDoc(doc(firebase.db, 'matchWindows', matchId))).data();
  await operations.recordNoShow(missing, expiredWindow, 'The squad did not enter the lobby before its scheduled deadline.');
  assert.equal((await getDoc(doc(firebase.db, 'matchCheckIns', `${matchId}__${missing.id}`))).data().status, 'no-show');

  let revision = tournament.revision;
  let updated = fromDocs(tournament, roster);
  updated.placement.games[0] = { ...updated.placement.games[0], scheduledDate: '2026-12-01', scheduledTime: '15:00' };
  revision = await saveTournament(updated, revision);
  updated.placement.games[0] = { ...updated.placement.games[0], status: 'completed', results: event.placement.teams.map((team, i) => ({ teamId: team.id, placement: i + 1, kills: i === 0 ? 8 : 0 })) };
  revision = await saveTournament(updated, revision);
  await saveTournament(updated, revision);
  const announcements = (await getDocs(collection(firebase.db, 'arenaAnnouncements'))).docs.map(item => item.data()).filter(item => item.entityId === matchId);
  assert.deepEqual(announcements.map(item => item.kind).sort(), ['result', 'schedule']);
  assert.ok(announcements.find(item => item.kind === 'result').body.includes('BR Squad 1 placed first'));
});
