// Applies institution.config.json to the parts of ArenaHub that cannot read it at runtime:
//   1. the email-domain policy blocks in firestore.rules and storage.rules
//   2. src/generated/institution.css, the school's brand colours as CSS custom properties
// Colours must pass WCAG AA against every dark surface, or this script fails (and with it dev and build).
// Usage: node scripts/sync-institution.mjs          write the files
//        node scripts/sync-institution.mjs --check  fail if any file is out of date
import { access, mkdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const check = process.argv.includes('--check');
const config = JSON.parse(await readFile(new URL('institution.config.json', root), 'utf8'));
if (!/^(?:[a-z0-9](?:[a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,}$/.test(config.emailDomain) || !config.name?.trim() || !config.shortName?.trim()) {
  throw new Error('Set a lowercase institutional emailDomain, name and shortName in institution.config.json.');
}

// ---------- 1. Security rules ----------
const regex = `[^@]+@${config.emailDomain.replaceAll('.', '[.]')}`;
const generated = `    // BEGIN INSTITUTION POLICY (generated by npm run configure:institution)\n    function institutionalEmail(email) {\n      return email is string && email.lower().matches('${regex}');\n    }\n    function acceptedGoogleIdentity() {\n      return request.auth.token.get('firebase', {}).get('sign_in_provider', '') != 'google.com'\n        || (request.auth.token.get('email_verified', false) == true && institutionalEmail(request.auth.token.get('email', '')));\n    }\n    // END INSTITUTION POLICY`;
for (const file of ['firestore.rules', 'storage.rules']) {
  const path = new URL(file, root), content = await readFile(path, 'utf8');
  const next = content.replace(/    \/\/ BEGIN INSTITUTION POLICY[^]*?    \/\/ END INSTITUTION POLICY/, generated);
  if (next === content && !content.includes(generated)) throw new Error(`Missing institution policy markers in ${file}`);
  if (check) {
    if (next !== content) throw new Error(`${file} is out of sync. Run npm run configure:institution.`);
  } else if (next !== content) await writeFile(path, next);
}

// ---------- 2. Theme ----------
// ArenaHub's own orange is the default, so a school that sets nothing looks exactly as before.
const DEFAULT_THEME = { primary: '#ff6600', accent: '#ff7a1f', primaryInk: '#ff8a3d', onPrimary: '#1a0b00', logo: '' };
const theme = { ...DEFAULT_THEME, ...(config.theme || {}) };
// Every surface brand colours appear on: page, panels, raised panels, hover, and the deeper "stage" surfaces.
const SURFACES = { page: '#0e0e10', panel: '#18181b', 'raised panel': '#1f1f23', hover: '#26262c', stage: '#0f0f12', 'stage panel': '#16161a' };

const hex = value => {
  if (typeof value !== 'string' || !/^#[0-9a-f]{6}$/i.test(value)) throw new Error(`Theme colours must be 6-digit hex like #ff6600. Got ${JSON.stringify(value)}.`);
  return [1, 3, 5].map(i => parseInt(value.slice(i, i + 2), 16));
};
const luminance = rgb => {
  const [r, g, b] = rgb.map(v => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const contrast = (a, b) => {
  const [x, y] = [luminance(hex(a)), luminance(hex(b))];
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);
};

const failures = [];
const need = (ratio, min, what) => { if (ratio < min) failures.push(`${what}: ${ratio.toFixed(2)}:1, needs ${min}:1`); };
for (const [name, surface] of Object.entries(SURFACES)) {
  // Text and links in the brand colour (WCAG 1.4.3, normal text).
  need(contrast(theme.primaryInk, surface), 4.5, `primaryInk text on the ${name} (${surface})`);
  // Active tabs, primary buttons and focus rings against the page (WCAG 1.4.11, UI components).
  need(contrast(theme.primary, surface), 3, `primary on the ${name} (${surface})`);
}
need(contrast(theme.onPrimary, theme.primary), 4.5, 'onPrimary button text on primary');
need(contrast(theme.onPrimary, theme.accent), 4.5, 'onPrimary button text on accent (hover)');
if (failures.length) {
  throw new Error(`institution.config.json theme fails WCAG AA contrast:\n  - ${failures.join('\n  - ')}\n`
    + 'Use a lighter primaryInk for text on dark surfaces, and an onPrimary that reads on both primary and accent.');
}

if (theme.logo) {
  if (!/^\/[a-z0-9][a-z0-9/_-]*\.(svg|png|webp)$/i.test(theme.logo) || theme.logo.includes('..')) {
    throw new Error('theme.logo must be a file in public/, written like /school-logo.svg (svg, png or webp).');
  }
  try { await access(new URL(`public${theme.logo}`, root)); }
  catch { throw new Error(`theme.logo ${theme.logo} was not found in public/.`); }
}

const rgba = (color, alpha) => `rgba(${hex(color).join(', ')}, ${alpha})`;
const css = `/* Generated by scripts/sync-institution.mjs from institution.config.json. Do not edit; run npm run configure:institution. */
/* Loaded after design.css, so these replace its brand tokens. Contrast was checked against every dark surface. */
:root, .app-shell, .auth-entry, .auth-entry-dialog, .auth-status-screen {
  --brand: ${theme.primary};
  --brand-hover: ${theme.accent};
  --brand-ink: ${theme.primaryInk};
  --brand-soft: ${rgba(theme.primary, '.16')};
  --brand-border: ${rgba(theme.accent, '.5')};
  --on-brand: ${theme.onPrimary};
  --focus: ${theme.primaryInk};
  --glow: 0 0 0 1px ${rgba(theme.primary, '.35')}, 0 8px 28px ${rgba(theme.primary, '.18')};
}
`;
const cssPath = new URL('src/generated/institution.css', root);
const current = await readFile(cssPath, 'utf8').catch(() => null);
if (check) {
  if (current !== css) throw new Error('src/generated/institution.css is out of sync. Run npm run configure:institution.');
} else if (current !== css) {
  await mkdir(new URL('src/generated/', root), { recursive: true });
  await writeFile(cssPath, css);
}
